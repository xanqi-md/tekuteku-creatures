# Retune balance, update js/balance-tuned.js, print a summary
$root = Split-Path $PSScriptRoot -Parent
$r = powershell -NoProfile -ExecutionPolicy Bypass -File "$PSScriptRoot\run-headless.ps1" -Page "$PSScriptRoot\balance.html" -Query '?tune' -WaitMs 560000 -Budget 5000
$pw = $r | Where-Object { $_ -like 'PW=*' }
$adj = $r | Where-Object { $_ -like 'ADJ=*' }
if ($pw) {
  $text = "// generated by tools/balance.html`nwindow.TK = window.TK || {};`nTK.PW = $($pw.Substring(3));`nTK.AREA_ADJ = $($adj.Substring(4));`n"
  [IO.File]::WriteAllText("$root\js\balance-tuned.js", $text, (New-Object Text.UTF8Encoding($false)))
}
$r | Where-Object { $_ -notlike 'PW=*' -and $_ -notlike 'ADJ=*' -and $_ -notlike '`[*' -and $_ -notlike 'verify*' }
'winrate min-max: ' + (($r | Where-Object { $_ -like 'verify*' } | ForEach-Object { [regex]::Match($_, 'min=([\d.]+)').Groups[1].Value + '-' + [regex]::Match($_, 'max=([\d.]+)').Groups[1].Value }) -join ' ')
